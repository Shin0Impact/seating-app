export type IconName = keyof typeof PATHS;

export function Icon({ name, size = 20 }: { name: IconName; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}

/** A button that shows only an icon; the name is its tooltip and screen reader label. */
export function IconButton(props: {
  icon: IconName;
  label: string;
  onClick: () => void;
  disabled?: boolean;
  danger?: boolean;
  pressed?: boolean;
  /** Small count shown on the corner of the button. */
  count?: number;
}) {
  const { icon, label, onClick, disabled, danger, pressed, count } = props;
  return (
    <button
      type="button"
      className={`icon-btn${danger ? ' danger' : ''}${pressed ? ' on' : ''}`}
      title={label}
      aria-label={label}
      aria-pressed={pressed}
      disabled={disabled}
      onClick={onClick}
    >
      <Icon name={icon} />
      {count !== undefined && <span className="icon-count">{count}</span>}
    </button>
  );
}
