export const SITE: Record<Lang, Record<SKey, string>> = { en, ar };

export type S = (k: SKey, vars?: Record<string, string | number>) => string;

export function makeS(lang: Lang): S {
  const d = SITE[lang];
  return (k, vars) => {
    let v = d[k];
    // text typed by people (names, venues) is wrapped in bidi isolates so Arabic and English never reorder each other
    if (vars)
      for (const [name, val] of Object.entries(vars))
        v = v.split(`{${name}}`).join(typeof val === 'string' && val ? `\u2068${val}\u2069` : String(val));
    return v;
  };
}

/** The locale used for dates and times. */
export const localeOf = (lang: Lang) => (lang === 'ar' ? 'ar' : 'en-GB');
